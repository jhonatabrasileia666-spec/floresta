  function makeVineRibbonGeometry(tree,count){
    const positions=[];
    const indices=[];
    const width=Math.max(.024,Math.min(.046,tree.radiusBottom*.10));
    let baseIndex=0;

    for(let strand=0;strand<count;strand++){
      const segments=18;
      const phase=
        (strand/Math.max(1,count))*Math.PI*2+
        treeHash(tree.index+strand*71)*.85;

      const turns=
        1.45+
        strand*.38+
        treeHash(tree.index+strand*19)*.55;

      const startY=.24+strand*.13;
      const endY=
        tree.height*
        (.58+Math.min(.19,strand*.075));

      for(let i=0;i<=segments;i++){
        const t=i/segments;
        const y=startY+(endY-startY)*t;
        const a=
          phase+
          turns*Math.PI*2*t+
          Math.sin(t*Math.PI*3+strand)*.11;

        const trunkR=
          tree.radiusBottom+
          (tree.radiusTop-tree.radiusBottom)*
          (y/tree.height);

        const r=trunkR+.022+strand*.006;

        const cx=Math.cos(a)*r;
        const cz=Math.sin(a)*r;

        const tx=-Math.sin(a)*width;
        const tz= Math.cos(a)*width;

        positions.push(cx-tx,y,cz-tz);
        positions.push(cx+tx,y,cz+tz);
      }

      for(let i=0;i<segments;i++){
        const a=baseIndex+i*2;
        const b=a+1;
        const c=a+2;
        const d=a+3;
        indices.push(a,c,b,b,c,d);
      }

      baseIndex+=(segments+1)*2;
    }

    const geo=new THREE.BufferGeometry();
    geo.setAttribute(
      "position",
      new THREE.Float32BufferAttribute(positions,3)
    );
    geo.setIndex(indices);
    geo.computeVertexNormals();
    geo.computeBoundingSphere();
    return geo;
  }

