  function angleDiff(a,b){return Math.atan2(Math.sin(a-b),Math.cos(a-b))}

  function makeNotchedTrunkGeometry(tree,progress){
    const source=trunkMesh.geometry.index?trunkMesh.geometry.toNonIndexed():trunkMesh.geometry.clone();
    const matrix=tree.barkMatrix,offset=tree.base;
    const cutY=Math.min(1,Math.max(.58,tree.height*.095)),half=Math.max(.18,tree.radiusBottom*.82);
    const planes=[cutY-half,cutY,cutY+half],triangles=[];
    const pos=source.attributes.position,norm=source.attributes.normal,uv=source.attributes.uv;
    const normalMatrix=new THREE.Matrix3().getNormalMatrix(matrix);
    function vertex(i){const local=new THREE.Vector3().fromBufferAttribute(pos,i);return {p:local.clone().applyMatrix4(matrix).sub(offset),n:new THREE.Vector3().fromBufferAttribute(norm,i).applyMatrix3(normalMatrix).normalize(),uv:new THREE.Vector2(uv?uv.getX(i):0,uv?uv.getY(i):0),local};}
    function interpolate(a,b,t){return {p:a.p.clone().lerp(b.p,t),n:a.n.clone().lerp(b.n,t).normalize(),uv:a.uv.clone().lerp(b.uv,t),local:a.local.clone().lerp(b.local,t)};}
    function clip(poly,y,above){const out=[];for(let i=0;i<poly.length;i++){const a=poly[i],b=poly[(i+1)%poly.length],ia=above?a.p.y>=y:a.p.y<=y,ib=above?b.p.y>=y:b.p.y<=y;if(ia)out.push(a);if(ia!==ib)out.push(interpolate(a,b,(y-a.p.y)/(b.p.y-a.p.y)));}return out;}
    for(let i=0;i<pos.count;i+=3){let pieces=[[vertex(i),vertex(i+1),vertex(i+2)]];for(const y of planes){const next=[];for(const poly of pieces){const low=Math.min(...poly.map(v=>v.p.y)),high=Math.max(...poly.map(v=>v.p.y));if(low<y-1e-6&&high>y+1e-6){for(const side of [false,true]){const q=clip(poly,y,side);if(q.length>=3)next.push(q);}}else next.push(poly);}pieces=next;}for(const poly of pieces)for(let j=1;j<poly.length-1;j++)triangles.push([poly[0],poly[j],poly[j+1]]);}
    const positions=[],normals=[],uvs=[],locals=[],groups=[];
    for(const tri of triangles){let affected=false;for(const v of tri){const center=new THREE.Vector3(0,v.local.y,0).applyMatrix4(matrix).sub(offset);const dx=v.p.x-center.x,dz=v.p.z-center.z,a=Math.atan2(dz,dx),angular=Math.max(0,1-Math.abs(angleDiff(a,tree.cutAngle))/(Math.PI*.31)),vertical=Math.max(0,1-Math.abs(v.p.y-cutY)/half),bite=progress*.78*angular*vertical;v.result=v.p.clone();v.result.x-=dx*bite;v.result.z-=dz*bite;v.bite=bite;affected=affected||bite>.001;}
      const face=new THREE.Vector3().subVectors(tri[1].result,tri[0].result).cross(new THREE.Vector3().subVectors(tri[2].result,tri[0].result)).normalize();
      const start=positions.length/3;
      for(const v of tri){positions.push(...v.result.toArray());normals.push(...(v.bite>.001?face:v.n).toArray());uvs.push(v.uv.x,v.uv.y);locals.push(...v.local.toArray());}
      groups.push({start,count:3,materialIndex:affected?1:0});
    }
    source.dispose();const geometry=new THREE.BufferGeometry();
    geometry.setAttribute('position',new THREE.Float32BufferAttribute(positions,3));geometry.setAttribute('normal',new THREE.Float32BufferAttribute(normals,3));geometry.setAttribute('uv',new THREE.Float32BufferAttribute(uvs,2));geometry.setAttribute('barkSourcePosition',new THREE.Float32BufferAttribute(locals,3));
    let last=null;for(const g of groups){if(last&&last.materialIndex===g.materialIndex)last.count+=g.count;else{last={...g};geometry.groups.push(last);}}geometry.computeBoundingSphere();return geometry;
  }

  function convertTree(tree){
    if(tree.converted)return;
    tree.converted=true;
    tree.barkMatrix=instanceWorld(trunkMesh,tree.index).clone();

    hideInstance(trunkMesh,tree.index);
    for(let a=0;a<3;a++)hideInstance(foliageMesh,tree.index*3+a);

    const pivot=new THREE.Group();
    pivot.name=`CuttableTree_${tree.index}`;
    pivot.position.copy(tree.base);
    scene.add(pivot);
    tree.pivot=pivot;

    tree.trunk=new THREE.Mesh(makeNotchedTrunkGeometry(tree,0),[cutBarkMaterial(tree),woodMaterial.clone()]);
    tree.trunk.castShadow=true;
    tree.trunk.receiveShadow=true;
    pivot.add(tree.trunk);

    // Recreate the original 3 foliage pieces at their exact world transforms.
    for(let a=0;a<3;a++){
      const fi=tree.index*3+a;
      const fm=instanceWorld(foliageMesh,fi);
      const fp=new THREE.Vector3(),fq=new THREE.Quaternion(),fs=new THREE.Vector3();
      fm.decompose(fp,fq,fs);
      const leaf=new THREE.Mesh(foliageMesh.geometry,cloneForestMaterial(foliageMesh.material));
      leaf.position.copy(fp).sub(tree.base);
      leaf.quaternion.copy(fq);
      leaf.scale.copy(fs);
      leaf.castShadow=true;
      tree.pivot.add(leaf);
    }
  }

  function updateNotch(tree){
    if(!tree.trunk)return;
    const progress=clamp(tree.hits/4,0,1);
    const old=tree.trunk.geometry;
    tree.trunk.geometry=makeNotchedTrunkGeometry(tree,progress);
    old?.dispose?.();
  }

  const chips=[];
