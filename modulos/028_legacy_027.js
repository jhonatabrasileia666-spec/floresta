  function makeCarryLog(tree){
    const len=clamp(tree.height*.42,2.75,3.65);
    const rad=clamp(tree.radiusBottom*.72,.17,.31);

    const bark=cloneForestMaterial(trunkMesh.material);
    const cutA=woodMaterial.clone();
    const cutB=woodMaterial.clone();

    // Slightly brighter cut ends so the carried trunk is readable in first person.
    cutA.color?.multiplyScalar?.(1.28);
    cutB.color?.multiplyScalar?.(1.18);
    bark.side=THREE.DoubleSide;
    cutA.side=THREE.DoubleSide;
    cutB.side=THREE.DoubleSide;

    const mesh=new THREE.Mesh(
      // V58: uniform-radius construction log.
      // The old tapered log (rad*.84 -> rad) could never sit flush along
      // another log: the thick end touched first and left a visible wedge gap.
      // A construction log now has the same outside radius along its length.
      new THREE.CylinderGeometry(rad,rad,len,18,4,false),
      [bark,cutA,cutB]
    );
    mesh.castShadow=true;
    mesh.receiveShadow=true;
    mesh.frustumCulled=false;
    mesh.renderOrder=4;
    mesh.userData.length=len;
    mesh.userData.radius=rad;

    // Small bark ridges make the side of the log easier to perceive close to camera.
    const ridgeMat=bark.clone();
    ridgeMat.color?.multiplyScalar?.(.78);
    for(let i=-2;i<=2;i++){
      const ring=new THREE.Mesh(
        new THREE.TorusGeometry(rad*.91,.012,5,18),
        ridgeMat
      );
      ring.rotation.x=Math.PI/2;
      ring.position.y=i*(len*.16);
      ring.castShadow=true;
      mesh.add(ring);
    }

    scene.add(mesh);
    return mesh;
  }

