  function updateCarry(){
    if(!carrying||!carryMesh||!rightShoulder)return;
    tfp.visibleRoot.updateMatrixWorld(true);

    const shoulder=new THREE.Vector3();
    rightShoulder.getWorldPosition(shoulder);

    const yaw=player.bodyYaw??player.yaw;
    const forward=new THREE.Vector3(-Math.sin(yaw),0,-Math.cos(yaw));
    const right=new THREE.Vector3(Math.cos(yaw),0,-Math.sin(yaw));
    const up=new THREE.Vector3(0,1,0);

    // IMPORTANT: V27 aligned the trunk almost exactly with the viewing direction.
    // In first person the player was looking down the length of the cylinder,
    // so it was practically invisible. V28 rests it diagonally across the
    // right shoulder: still lumberjack-like, but its side is clearly visible.
    const axis=forward.clone().multiplyScalar(.78)
      .addScaledVector(right,.58)
      .addScaledVector(up,.075)
      .normalize();
    const qlog=new THREE.Quaternion().setFromUnitVectors(up,axis);

    // Put the log genuinely on the OUTER part of the right shoulder rather
    // than inside the neck/camera volume.
    const center=shoulder.clone()
      .addScaledVector(right,.30)
      .addScaledVector(forward,.20)
      .addScaledVector(up,.17);

    // Safety against near-plane / head clipping. If the log axis passes too
    // close to the camera, move the whole trunk outward while preserving its
    // shoulder position and orientation.
    game.camera.getWorldPosition(carryCamPos);
    carryTmp.copy(carryCamPos).sub(center);
    const along=carryTmp.dot(axis);
    carryClosest.copy(center).addScaledVector(axis,along);
    const cameraClearance=carryCamPos.distanceTo(carryClosest);
    const desiredClearance=(carryMesh.userData.radius||.22)+.22;
    if(cameraClearance<desiredClearance){
      center.addScaledVector(right,desiredClearance-cameraClearance+.06);
    }

    carryMesh.visible=true;
    carryMesh.position.lerp(center,.58);
    carryMesh.quaternion.slerp(qlog,.50);
    carryMesh.updateMatrixWorld(true);

    // Right hand actually supports the underside/front third of the log.
    const handTarget=center.clone()
      .addScaledVector(axis,.62)
      .addScaledVector(up,-(carryMesh.userData.radius||.22)*.72)
      .addScaledVector(right,-.04);

    armIK(rightArm,rightFore,rightHand,handTarget);
    shadowIK(handTarget);
  }

